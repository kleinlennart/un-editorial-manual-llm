"""Stage Quarto site inputs from the manifest, render, and add raw Markdown + llms files."""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import yaml

from .manifest import Manifest


def _site_page(raw: str, page) -> str:
    body = Manifest.strip_front_matter(raw)
    body = re.sub(r"^# .*\n+", "", body, count=1)  # Quarto renders the title itself
    md_name = Path(page.path).name
    note = (
        '::: {.source-note}\n'
        f'Source: [{page.source_url}]({page.source_url}) · '
        f'Last changed upstream: {page.last_changed} · '
        f'[Markdown]({md_name})\n'
        ':::\n\n'
    )
    meta = {"title": page.title, "description": page.description or None}
    meta = {k: v for k, v in meta.items() if v}
    return "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000) + "---\n\n" + note + body


def stage(root: Path) -> None:
    site = root / "site"
    manifest = Manifest.load(root / "manifest.json")
    assert manifest is not None, "run `unem build` first"
    lang_dir = site / manifest.language
    if lang_dir.exists():
        shutil.rmtree(lang_dir)
    for p in manifest.pages:
        src = root / "content" / p.path
        dst = site / p.path
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(_site_page(src.read_text(encoding="utf-8"), p), encoding="utf-8")

    contents = []
    for g in manifest.groups:
        items = [{"href": p.path, "text": p.title} for p in manifest.pages_in_group(g)]
        if items:
            contents.append({"section": g, "contents": items})
    sidebar = {
        "website": {
            "sidebar": {
                "style": "docked",
                "search": True,
                "contents": [{"href": "index.qmd", "text": "About this mirror"}, *contents],
            }
        }
    }
    (site / "_sidebar.yml").write_text(
        "# generated by `unem site`; do not edit\n" + yaml.safe_dump(sidebar, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )


def render(root: Path) -> Path:
    site = root / "site"
    subprocess.run(["quarto", "render", str(site)], check=True)
    out = site / "_site"
    # Raw Markdown next to each rendered page (llms.txt convention: page.html → page.md).
    manifest = Manifest.load(root / "manifest.json")
    for p in manifest.pages:
        dst = out / p.path
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / "content" / p.path, dst)
    for name in ("llms.txt", "llms-full.txt"):
        shutil.copyfile(root / name, out / name)
    (out / ".nojekyll").touch()
    return out
